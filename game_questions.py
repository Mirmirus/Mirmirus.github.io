def validate_questions_answers(questions, answers):
    ok = True

    print("=== ПРОВЕРКА НАБОРОВ ===")

    if len(questions) != len(answers):
        print(f"❌ Разное количество наборов")
        print(f"questions: {len(questions)}")
        print(f"answers:   {len(answers)}")
        ok = False

    sets_count = min(len(questions), len(answers))

    for set_index in range(sets_count):
        print(f"\n--- НАБОР {set_index} ---")

        q_rounds = questions[set_index]
        a_rounds = answers[set_index]

        if len(q_rounds) != len(a_rounds):
            print(f"❌ Разное количество раундов")
            print(f"questions: {len(q_rounds)}")
            print(f"answers:   {len(a_rounds)}")
            ok = False

        rounds_count = min(len(q_rounds), len(a_rounds))

        for round_index in range(rounds_count):
            print(f"  Раунд {round_index}")

            try:
                round_answers = a_rounds[round_index][0]
                round_scores = a_rounds[round_index][1]
            except Exception:
                print("  ❌ Неверная структура ответов")
                ok = False
                continue

            if len(round_answers) != len(round_scores):
                print("  ❌ Количество ответов != количеству очков")
                print("  ответы:", len(round_answers))
                print("  очки:  ", len(round_scores))
                ok = False

    print("\n=== РЕЗУЛЬТАТ ===")
    if ok:
        print("✅ ВСЁ КОРРЕКТНО")
    else:
        print("❌ НАЙДЕНЫ ОШИБКИ")

    return ok

